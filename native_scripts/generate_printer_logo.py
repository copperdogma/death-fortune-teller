#!/usr/bin/env python3
"""Generate the embedded half-size logo from the original 1-bit BMP (no dependencies)."""
from pathlib import Path
import hashlib
import struct

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'sd-card-files/printer/logo_384w.bmp'
bmp = source.read_bytes()
offset = struct.unpack_from('<I', bmp, 10)[0]
width, height = struct.unpack_from('<ii', bmp, 18)
assert (width, height) == (384, 353)
assert struct.unpack_from('<H', bmp, 28)[0] == 1
assert struct.unpack_from('<I', bmp, 30)[0] == 0
assert bmp[54:62] == bytes([255, 255, 255, 0, 0, 0, 0, 0])
stride = ((width + 31) // 32) * 4

def black(x, y):
    if y >= height:
        return 0
    return (bmp[offset + (height - 1 - y) * stride + x // 8] >> (7 - x % 8)) & 1

# 2x2 area reduction, black at >=50% coverage; final odd row pads white.
out_width, out_height = width // 2, (height + 1) // 2
pixels = bytearray(out_width // 8 * out_height)
for y in range(out_height):
    for x in range(out_width):
        coverage = sum(black(2*x+dx, 2*y+dy) for dy in range(2) for dx in range(2))
        if coverage >= 2:
            pixels[y * (out_width // 8) + x // 8] |= 1 << (7 - x % 8)
lines = [
    '#pragma once', '#include <cstddef>', '#include <cstdint>', '#include <cstring>', '',
    '// Generated by native_scripts/generate_printer_logo.py; original BMP is preserved.',
    '// Source SHA256: ' + hashlib.sha256(bmp).hexdigest(),
    '// Half width/height: 192x177 pixels, 2x2 area reduction (>=50% black).',
    'namespace skull::printer::detail::logo {',
    f'inline constexpr unsigned width_bytes = {out_width // 8}, height = {out_height};',
    'inline constexpr size_t packet_bytes = 8 + width_bytes;',
    'inline constexpr char pixels[] =',
]
for start in range(0, len(pixels), 32):
    lines.append('    "' + ''.join(f'\\x{b:02x}' for b in pixels[start:start+32]) + '"')
lines[-1] += ';'
lines += ['static_assert(sizeof(pixels) == width_bytes * height + 1);', '',
    '// Complete one-row packets preserve cancellation framing.',
    'inline bool row_packet(unsigned row, uint8_t (&packet)[packet_bytes]) {',
    '    if (row >= height) return false;',
    '    const uint8_t header[] = {0x1d, 0x76, 0x30, 0x00, width_bytes, 0x00, 0x01, 0x00};',
    '    std::memcpy(packet, header, sizeof(header));',
    '    std::memcpy(packet + sizeof(header), pixels + row * width_bytes, width_bytes);',
    '    return true;', '}', '} // namespace skull::printer::detail::logo', '']
(ROOT / 'firmware/main/death_printer_logo.h').write_text('\n'.join(lines))
hash_value = 2166136261
for b in pixels:
    hash_value = ((hash_value ^ b) * 16777619) & 0xffffffff
print(f'{out_width}x{out_height}; pixel FNV1a {hash_value:08x}; logo wire+pacing {out_height*(32*10/9600+.05):.2f}s')
